#!/usr/bin/env python3
"""Draws the portal's smoke puff from a fixed seed, and writes it as a TypeScript data URL.

Reads no source image. Needs Pillow and NumPy. Run from the kit's root folder.
"""
import base64
import io
import numpy as np
from PIL import Image, ImageFilter

SIZE = 256
rng = np.random.default_rng(8033)

def layer(cells):
    # Smooth noise: a small random grid, enlarged.
    grid = rng.random((cells, cells))
    img = Image.fromarray((grid * 255).astype("uint8"))
    return np.asarray(img.resize((SIZE, SIZE), Image.BICUBIC), dtype=float) / 255

noise = sum(layer(c) * w for c, w in [(5, .5), (10, .27), (20, .15), (40, .08)])
noise = (noise - noise.min()) / (noise.max() - noise.min())

# Billows: bright overlapping lumps, so it reads as smoke rather than fog.
y, x = np.mgrid[0:SIZE, 0:SIZE]
lumps = np.zeros((SIZE, SIZE))
for _ in range(70):
    a, r = rng.random() * 2 * np.pi, (rng.random() ** .6) * SIZE * .39
    cx, cy = SIZE / 2 + r * np.cos(a), SIZE / 2 + r * np.sin(a)
    s = SIZE * (.025 + rng.random() * .04)
    lumps = np.maximum(lumps, (0.45 + rng.random() * .55) * np.exp(-((x - cx) ** 2 + (y - cy) ** 2) / (2 * s * s)))

# Fades to black at the edge, because the particles are drawn additively.
# The edge is ragged, so the puffs overlap into an uneven outline.
d = np.hypot(x - SIZE / 2, y - SIZE / 2) / (SIZE / 2) + (layer(9) - .5) * .42
falloff = np.clip((1 - d ** 3) * 1.6, 0, 1)

value = (lumps * .85 + noise * .25) * falloff * (0.6 + noise * .6)
value = np.clip(value / value.max(), 0, 1) ** 1.05 * 0.85
out = Image.fromarray((value * 255).astype("uint8")).filter(ImageFilter.GaussianBlur(.7))
buffer = io.BytesIO()
out.convert("RGB").save(buffer, "PNG", optimize=True)
encoded = base64.b64encode(buffer.getvalue()).decode()
with open("src/xr/portalSmokeTexture.ts", "w") as ts:
    ts.write("// Generated by scripts/generate-smoke.py.\n")
    ts.write(f'export const PORTAL_SMOKE_TEXTURE = "data:octet/stream;base64,{encoded}";\n')
